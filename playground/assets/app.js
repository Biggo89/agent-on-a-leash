  function boot() {
    buildViews();

    $$(".viewswitch button").forEach((b) =>
      b.addEventListener("click", () => {
        setView(b.dataset.view, true);
        window.scrollTo({ top: 0, behavior: "smooth" });
      })
    );

    /* Theme toggle — explicit choice beats the OS in both directions. */
    const root = document.documentElement;
    let stored = null;
    try {
      stored = localStorage.getItem("wcl-theme");
    } catch (err) {
      /* ignore */
    }
    if (stored) root.dataset.theme = stored;

    $("#theme").addEventListener("click", () => {
      const dark =
        root.dataset.theme === "dark" ||
        (!root.dataset.theme && window.matchMedia("(prefers-color-scheme: dark)").matches);
      root.dataset.theme = dark ? "light" : "dark";
      try {
        localStorage.setItem("wcl-theme", root.dataset.theme);
      } catch (err) {
        /* ignore */
      }
    });

    /* A deep link decides the view; otherwise the last one used. */
    const hash = location.hash.slice(1);
    let view = "guided";
    if (hash.startsWith("e-")) view = "eng";
    else if (!hash) {
      try {
        view = localStorage.getItem("wcl-view") || "guided";
      } catch (err) {
        view = "guided";
      }
    }
    setView(view, false);
    if (hash && document.getElementById(hash)) {
      document.getElementById(hash).scrollIntoView();
    }

    $("#board-count").textContent = EVENTS.length;
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot);
  } else {
    boot();
  }
