  /* Ported verbatim from domain/sanitize.py. Same patterns, same labels, same excerpt window. */
  const PATTERNS = [
    [/ignore\s+(?:any\s+|all\s+)?(?:previous|prior|earlier)\s+\w*\s*instructions/gim, "override_instructions"],
    [/^\s*system\s*:/gim, "fake_system_prompt"],
    [/\bnote\s+for\s+(?:automated|ai|purchasing)\b/gim, "addressed_to_agent"],
    [/\bpre-?author(?:ised|ized)\b/gim, "claimed_preauthorization"],
    [/\blimits?\s+(?:do\s+not|don'?t)\s+apply\b/gim, "claimed_limit_exemption"],
    [/\bapprove\b[^.]{0,60}\b(?:immediately|now|without)\b/gim, "demands_approval"],
    [/\bwithout\s+further\s+(?:checks|verification|review)\b/gim, "demands_no_checks"],
    [/\bcardholder\s+is\s+(?:unavailable|not\s+available)\b/gim, "claims_owner_absent"],
    [/\bdo\s+not\s+(?:ask|confirm|verify|check)\b/gim, "demands_no_confirmation"],
    [/\b(?:bypass|skip|disregard|override)\b[^.]{0,40}\b(?:check|limit|rule|policy|control)/gim, "demands_bypass"],
  ];

  const RETURN_DAYS = /return(?:s|ed|able)?[^.;]{0,40}?(\d{1,3})\s*day/i;
  const SIZE_RE = /\bsize\s+(\d{1,3})\b/i;
  const FINAL_SALE = /\b(?:final\s+sale|no\s+returns|non-?returnable)\b/i;
  const POLICY_ABSENT = /return\s+policy\s+not\s+stated/i;

  function detect(text) {
    const hits = [];
    PATTERNS.forEach(([re, label]) => {
      re.lastIndex = 0;
      let m;
      while ((m = re.exec(text)) !== null) {
        const s = Math.max(0, m.index - 20);
        const e = Math.min(text.length, m.index + m[0].length + 40);
        hits.push({ label, excerpt: text.slice(s, e).trim(), span: [m.index, m.index + m[0].length] });
        if (m[0] === "") re.lastIndex++;
      }
    });
    return hits;
  }

  function extractFacts(text) {
    const days = RETURN_DAYS.exec(text);
    const size = SIZE_RE.exec(text);
    const finalSale = FINAL_SALE.test(text);
    let stated = Boolean(days) || finalSale;
    if (POLICY_ABSENT.test(text)) stated = false;
    return {
      return_window_days: days ? parseInt(days[1], 10) : null,
      size: size ? parseInt(size[1], 10) : null,
      final_sale: finalSale,
      return_policy_stated: stated,
    };
  }

