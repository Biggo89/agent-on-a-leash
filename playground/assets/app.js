  /* Highlight the section currently in view. */
  let observer = null;
  function observeSections(view) {
    if (observer) observer.disconnect();
    const root = view === "guided" ? $("#view-guided") : $("#view-eng");
    const seen = new Map();
    observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((en) => seen.set(en.target.id, en.intersectionRatio));
        let best = null;
        let bestRatio = 0;
        seen.forEach((r, id) => {
          if (r > bestRatio) {
            bestRatio = r;
            best = id;
          }
        });
        if (!best) return;
        $$("#rail-nav a").forEach((a) => a.classList.toggle("on", a.dataset.target === best));
      },
      { rootMargin: "-70px 0px -55% 0px", threshold: [0, 0.15, 0.4, 0.75, 1] }
    );
    $$("section.sec", root).forEach((s) => observer.observe(s));
  }

  function setView(view, push) {
    $("#view-guided").hidden = view !== "guided";
    $("#view-eng").hidden = view !== "eng";
    $$(".viewswitch button").forEach((b) =>
      b.setAttribute("aria-selected", String(b.dataset.view === view))
    );
    buildRail(view);
    observeSections(view);
    document.documentElement.dataset.view = view;
    try {
      localStorage.setItem("wcl-view", view);
    } catch (err) {
      /* private mode — the view simply doesn't persist */
    }
    if (push) history.replaceState(null, "", "#" + (view === "guided" ? "g-what" : "e-map"));
  }

