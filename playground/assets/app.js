  /* Minimal Python highlighter — enough for short illustrative excerpts. */
  const PY_KEYWORDS =
    /\b(def|return|if|elif|else|for|in|not|and|or|None|True|False|class|import|from|raise|try|except|is|pass|lambda|dataclass|frozen|slots)\b/g;

  function py(src) {
    const lines = esc(src).split("\n");
    return lines
      .map((line) => {
        const hash = line.indexOf("#");
        let code = line;
        let comment = "";
        if (hash > -1 && (line.slice(0, hash).match(/"/g) || []).length % 2 === 0) {
          code = line.slice(0, hash);
          comment = line.slice(hash);
        }
        code = code
          .replace(/(&quot;[^&]*?&quot;|'[^']*?')/g, '<span class="s">$1</span>')
          .replace(PY_KEYWORDS, '<span class="k">$1</span>')
          .replace(/\b([a-z_][a-z0-9_]*)\(/g, '<span class="f">$1</span>(');
        return code + (comment ? `<span class="c">${comment}</span>` : "");
      })
      .join("\n");
  }

  function codeBlock(src) {
    return `<pre class="code">${py(src)}</pre>`;
  }

